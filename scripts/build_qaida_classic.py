def cells(items, cols, cls=""):
    rows = -(-len(items) // cols)
    return (f'<div class="grid c{cols} {cls}" style="flex:{rows}">' + "".join(
        f'<div class="cell"><span class="ar" lang="ar">{a}</span>' + (f'<span class="nm" lang="ur">{n}</span>' if n else "") + "</div>"
        for a, n in items) + "</div>")


def page(num, ur_title, en_title, ur_note, en_note, body):
    return (f'<section class="pg"><div class="frame"><header><span class="sabaq" lang="ur">سبق نمبر {str(num).translate(UD)}</span>'
            f'<h2 lang="ur">{ur_title}</h2><span class="en">Lesson {num} · {en_title}</span></header>'
            f'<div class="body">{body}</div>'
            f'<div class="note"><p class="ur-note" lang="ur" dir="rtl"><b>ہدایت:</b> {ur_note}</p><p class="en-note">{en_note}</p></div>'
            f'<footer>Noorani Qaida · quranonlinetarteel.net</footer></div></section>')


def harakat_rows(marks):
    out = []
    for l in ALL:
        for h in marks:
            b = ("إ" if h in (K, KT) else "أ") if l == "ا" else l
            if l == "ء":
                b = "ء"
            out.append((b + h, ""))
    return out


def surah(n, size=29):
    vs = Q[n - 1]["verses"]
    body = "".join(f'{v["text"]} <span class="an">({str(v["id"]).translate(AD)})</span> ' for v in vs)
    bism = "" if n in (1, 9) else '<p class="bism">بِسۡمِ ٱللَّهِ ٱلرَّحۡمَٰنِ ٱلرَّحِيمِ</p>'
    return (f'<div class="surah"><h3><span lang="ur">سورۃ</span> {Q[n - 1]["name"]} <small>Surah {Q[n - 1]["transliteration"]}</small></h3>'
            f'{bism}<p class="ayat" lang="ar" dir="rtl" style="font-size:{size}px">{body}</p></div>')


